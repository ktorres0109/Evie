import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs'
import { SHOTS, APP, RELAY } from './env.mjs'
const OUT = SHOTS
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const p = await (await b.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 2, locale: 'en-US' })).newPage()
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
await p.goto(APP, { waitUntil: 'networkidle' })
const primary = () => p.locator('.mz-btn--primary').last().click()
await p.locator('button').filter({ hasText: /^Me/ }).first().click()
for (const c of await p.getByRole('checkbox').all()) await c.check(); await primary(); await primary()
await p.locator('input[type=date]').fill(new Date(Date.now() - 20 * 864e5).toISOString().slice(0, 10)); await primary()
await p.getByRole('radio', { name: /^Pill/ }).click(); await primary()
await primary(); await p.locator('.mz-btn--ghost').last().click()
await p.waitForTimeout(700)
const today = () => p.locator('main').innerText()
console.log('card shown:', (await today()).includes('Finish setting up birth control'))
await p.screenshot({ path: `${OUT}/96-method-card.png` })
await p.getByRole('button', { name: 'Set it up' }).click()
await p.waitForTimeout(400)
await p.getByRole('button', { name: 'Finish setup' }).click()
await p.waitForTimeout(300)
await p.locator('.mz-sheet .mz-list-row').first().click()   // first choice: combined pill
await p.waitForTimeout(400)
await p.screenshot({ path: `${OUT}/97-method-setup.png` })
const dates = p.locator('[role=dialog]').last().locator('input[type=date]')
console.log('date fields:', await dates.count())
if (await dates.count() > 1) await dates.nth(1).fill(new Date(Date.now() - 9 * 864e5).toISOString().slice(0, 10))
await p.locator('[role=dialog]').last().locator('.mz-btn--primary').last().click()
await p.waitForTimeout(600)
const regs = await p.evaluate(async () => (await import('/src/db/schema.ts')).db.regimenRecords.toArray())
console.log('regimens:', regs.length, JSON.stringify(regs.map((r) => [r.method, r.startDate, r.endDate, r.config?.kind, r.config?.currentPackStart])))
console.log('pending flag:', await p.evaluate(async () => (await import('/src/db/schema.ts')).getSetting('method.setupPending')))
await p.locator('.mz-appbar--back button').first().click(); await p.waitForTimeout(500)
const t = await today()
console.log('card gone:', !t.includes('Finish setting up'), '| hero:', t.split('\n').slice(0, 4).join(' / '))
await p.screenshot({ path: `${OUT}/98-today-pill.png` })
console.log('errs', errs)
await b.close()
